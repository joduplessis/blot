import type { Tag } from '@/types'

export const tagPath = (tags: Tag[], tag: Tag): string => {
    const parent = tags.find((item) => item.id === tag.parentId)
    return parent ? `${tagPath(tags, parent)} / ${tag.text}` : tag.text
}

